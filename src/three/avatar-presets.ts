/** バランスよく わくわくする ランダムアバターを作る。 */
export function buildRandomAvatar(
  mode: "suit" | "free",
  allHair: HairStyle[],
): Partial<AvatarConfig> {
  const female = Math.random() < 0.5;
  const outfit =
    mode === "suit"
      ? "suit"
      : pick<AvatarConfig["outfit"]>(["casual", "casual", "casual", "kigurumi", "suit"]);
  const gl =
    mode === "suit" ? pick<GlassesStyle>(["none", "none", "round", "square"]) : pick(RAND_GLASSES);
  const cheek = pick(RAND_CHEEKS);
  const bagStyle = outfit === "casual" ? pick(RAND_BAGS) : "none";
  return {
    outfit,
    kigurumi: pick(RAND_KIGS),
    casualStyle: pick(RAND_CASUALS),
    figure: female ? "f" : "m",
    bottom: female ? (Math.random() < 0.55 ? "skirt" : "pants") : "pants",
    height: 155 + Math.round(Math.random() * 28),
    skin: pick(RAND_SKINS),
    hair: pick(RAND_HAIRS),
    hairStyle: pick(allHair),
    eyes: pick(RAND_EYES),
    eyeColor: pick(RAND_EYE_COLORS),
    eyebrow: pick(RAND_BROWS),
    nose: pick(RAND_NOSES),
    mouth: pick(RAND_MOUTHS),
    cheek,
    blush: cheek !== "none",
    faceMark: mode === "suit" ? "none" : pick(RAND_MARKS),
    hat: mode === "suit" ? "none" : pick(RAND_HATS),
    hatColor: pick(RAND_COLORS),
    glasses: gl !== "none",
    glassesStyle: gl,
    glassesColor: pick(["#2a2d35", "#4a3326", "#c9a227", "#3b6ea5", "#e85c7a"]),
    accessory:
      mode === "suit"
        ? pick(["none", "none", "earrings"] as const)
        : pick(["none", "none", "flower", "ribbon", "starClip", "earrings", "sprout"] as const),
    neckwear: mode === "suit" ? "none" : pick(RAND_NECKS),
    neckColor: pick(["#c83e4d", "#2c3e70", "#6fbf9a", "#9b7fd1", "#e8965a"]),
    bag: bagStyle !== "none",
    bagStyle,
    bagColor: pick(["#2b2f37", "#8a5a3b", "#f4c7c3", "#ffffff", "#3b6ea5"]),
    suit: pick(["#1c1e24", "#232f52", "#3a3d45", "#5b616c"]),
    tie: pick(["#1f3f7a", "#8a1c2b", "#2d5e3a", "#5a3e8a", "#c9a227", "#e85c7a"]),
    shirt: pick(["#f4f6f8", "#dfefff", "#fff2f7", "#fdf3dc"]),
    coat: pick(RAND_COLORS),
    pants: pick(["#3a3d44", "#2a3550", "#6b5a45", "#4a6a8a", "#c9b79c", "#f2efe8"]),
    shoeType: outfit === "suit" ? "leather" : pick(["sneaker", "sneaker", "sandal", "leather"]),
    shoes:
      outfit === "suit" ? "#24201f" : pick(["#f4f4f2", "#24201f", "#3b6ea5", "#f6a6b8", "#e8c547"]),
  };
}
